// Scans public/site/ and records which file backs each slot (matched by base name, any extension).
// Runs automatically before `npm run dev` / `npm run build`. Re-run with `npm run assets`.
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, extname, basename } from "node:path";

const dir = join(process.cwd(), "public", "site");
const OK = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif", ".mp4", ".webm"]);
const best = new Map();
for (const f of readdirSync(dir)) {
  const ext = extname(f).toLowerCase();
  if (!OK.has(ext)) continue;
  const base = basename(f, extname(f)).trim().toLowerCase(); // tolerate "hero-mobile .png"
  if (base === "no-photo") continue;
  const t = statSync(join(dir, f)).mtimeMs;
  if (!best.has(base) || t > best.get(base).t) best.set(base, { f, t });
}
const files = Object.fromEntries([...best].sort().map(([k, v]) => [k, v.f]));
writeFileSync(
  join(process.cwd(), "src", "lib", "site-assets.generated.ts"),
  `// AUTO-GENERATED by scripts/scan-site-assets.mjs. Do not edit.\nexport const FILES: Record<string, string> = ${JSON.stringify(files, null, 2)};\n`,
);
console.log(`site assets: ${Object.keys(files).length} found (${Object.keys(files).join(", ")})`);
